import { fileURLToPath } from "node:url";
import { Effect, FileSystem } from "effect";
import { NodeRuntime, NodeServices } from "@effect/platform-node";

/**
 * Embeds the checked runtime template at build time. The public generator imports
 * a string module, so installed packages need neither source files nor runtime IO.
 */
const embedRuntime = Effect.gen(function* embedRuntimeTemplate() {
  const fs = yield* FileSystem.FileSystem;
  const sources: Record<string, string> = {};
  for (const name of [
    "basic",
    "api-key-header",
    "api-key-query",
    "api-key-cookie",
    "body",
    "errors",
    "http",
    "url",
    "error-credential-unavailable",
    "error-invalid-basic-credential",
    "error-basic-encoding-error",
    "error-cookie-configuration-error",
    "error-cookie-encoding-error",
    "error-api-key-preparation-error",
  ]) {
    const source = yield* fs.readFileString(
      fileURLToPath(new URL(`../src/core/templates/${name}.ts`, import.meta.url)),
    );
    if (name === "errors") {
      for (const marker of ["declarations", "case"]) {
        if (source.split(`/* template:authentication-${marker} */`).length !== 2) {
          return yield* Effect.fail(
            new Error(`Expected one authentication ${marker} template marker.`),
          );
        }
      }
    }

    sources[name] = source.includes("// template:body\n")
      ? (source.split("// template:body\n")[1] ?? "")
      : source;
  }
  const destination = fileURLToPath(
    new URL("../src/core/runtime-source.generated.ts", import.meta.url),
  );
  yield* fs.writeFileString(
    destination,
    `// Generated by tools/embed-runtime.ts. Do not edit.\nexport const runtimeSources = ${JSON.stringify(sources)};\n`,
  );

  return yield* Effect.void;
});

embedRuntime.pipe(
  Effect.provide(NodeServices.layer),
  NodeRuntime.runMain({ disableErrorReporting: true }),
);
