import { BunRuntime, BunServices } from "@effect/platform-bun";
import { Array as Arr, Effect, FileSystem, Order, Path, pipe } from "effect";
import type { PlatformError } from "effect/PlatformError";

const header = "// Generated by tools/embed-runtime.ts. Do not edit.\n";

const declaration = "export const runtimeFiles: Readonly<Record<string, string>>";

const count = (text: string, character: string): number => text.split(character).length - 1;

/**
 * Print a string literal as the formatter does: double quotes unless the text holds more double
 * than single quotes, in which case single quotes.
 */
const literal = (text: string): string => {
  const json = JSON.stringify(text);

  return count(text, '"') <= count(text, "'")
    ? json
    : `'${json.slice(1, -1).replaceAll('\\"', '"').replaceAll("'", "\\'")}'`;
};

/**
 * Render the module text for every file under `runtimeSrcDir`: whole file contents keyed by the
 * path relative to that directory (`/` separators), sorted. A missing or empty directory yields an
 * empty map. The layout is the one `vp fmt --check` accepts: one entry per line, trailing commas.
 */
export const embedRuntime = (
  runtimeSrcDir: string,
): Effect.Effect<string, PlatformError, FileSystem.FileSystem | Path.Path> =>
  Effect.gen(function* embedFiles() {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;

    if (!(yield* fs.exists(runtimeSrcDir))) {
      return `${header}${declaration} = {};\n`;
    }

    const entries = yield* fs.readDirectory(runtimeSrcDir, { recursive: true });
    const files = yield* pipe(
      entries,
      Effect.filter((entry) =>
        fs.stat(path.join(runtimeSrcDir, entry)).pipe(Effect.map((info) => info.type === "File")),
      ),
    );
    const keys = Arr.sort(
      files.map((file) => file.split(path.sep).join("/")),
      Order.String,
    );

    if (keys.length === 0) {
      return `${header}${declaration} = {};\n`;
    }

    const lines = yield* pipe(
      keys,
      Effect.forEach((key) =>
        fs
          .readFileString(path.join(runtimeSrcDir, ...key.split("/")))
          .pipe(Effect.map((content) => `  ${literal(key)}: ${literal(content)},\n`)),
      ),
    );

    return `${header}${declaration} = {\n${lines.join("")}};\n`;
  });

const embed = Effect.gen(function* embedToDisk() {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const root = path.resolve(import.meta.dir, "..");
  const text = yield* embedRuntime(path.join(root, "src", "runtime-src"));

  const emitDir = path.join(root, "src", "emit");

  yield* fs.makeDirectory(emitDir, { recursive: true });
  yield* fs.writeFileString(path.join(emitDir, "runtime-files.generated.ts"), text);
});

if (import.meta.main) {
  BunRuntime.runMain(embed.pipe(Effect.provide(BunServices.layer)));
}
