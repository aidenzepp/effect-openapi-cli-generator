import { describe, expect, test } from "bun:test";
import { BunFileSystem, BunPath } from "@effect/platform-bun";
import { Effect, FileSystem, Layer, Path } from "effect";
import { embedRuntime } from "../../tools/embed-runtime.ts";

const layer = Layer.mergeAll(BunFileSystem.layer, BunPath.layer);

const header = "// Generated by tools/embed-runtime.ts. Do not edit.\n";

const run = <A, E>(
  body: (
    dir: string,
    fs: FileSystem.FileSystem,
    path: Path.Path,
  ) => Effect.Effect<A, E, FileSystem.FileSystem | Path.Path>,
) =>
  Effect.runPromise(
    Effect.scoped(
      Effect.gen(function* step1() {
        const fs = yield* FileSystem.FileSystem;
        const path = yield* Path.Path;
        const dir = yield* fs.makeTempDirectoryScoped({ prefix: "em6-" });

        return yield* body(dir, fs, path);
      }),
    ).pipe(Effect.provide(layer)),
  );

describe("embedRuntime", () => {
  test("a tree with files in nested directories yields a sorted map with exact contents", async () => {
    const text = await run((dir, fs, path) =>
      Effect.gen(function* step2() {
        yield* fs.makeDirectory(path.join(dir, "runtime"), { recursive: true });
        yield* fs.writeFileString(path.join(dir, "runtime", "b.ts"), 'export const b = "x\\n";\n');
        yield* fs.writeFileString(path.join(dir, "a.ts"), "export const a = 1;\n");

        return yield* embedRuntime(dir);
      }),
    );

    expect(text).toBe(
      `${header}export const runtimeFiles: Readonly<Record<string, string>> = {\n` +
        `  "a.ts": ${JSON.stringify("export const a = 1;\n")},\n` +
        `  "runtime/b.ts": 'export const b = "x\\\\n";\\n',\n` +
        "};\n",
    );
  });

  test("string literals use the quote style the formatter prints", async () => {
    const text = await run((dir, fs, path) =>
      Effect.gen(function* step2() {
        yield* fs.writeFileString(path.join(dir, "q.ts"), 'import { A } from "effect";\n');
        yield* fs.writeFileString(path.join(dir, "s.ts"), "it's\n");

        return yield* embedRuntime(dir);
      }),
    );

    expect(text).toContain(`  "q.ts": 'import { A } from "effect";\\n',\n`);
    expect(text).toContain(`  "s.ts": "it's\\n",\n`);
  });

  test("a missing directory yields an empty map", async () => {
    const text = await run((dir, _fs, path) => embedRuntime(path.join(dir, "absent")));

    expect(text).toBe(
      `${header}export const runtimeFiles: Readonly<Record<string, string>> = {};\n`,
    );
  });

  test("an empty directory yields an empty map", async () => {
    const text = await run((dir) => embedRuntime(dir));

    expect(text).toBe(
      `${header}export const runtimeFiles: Readonly<Record<string, string>> = {};\n`,
    );
  });
});
